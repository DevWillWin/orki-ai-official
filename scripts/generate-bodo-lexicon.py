#!/usr/bin/env python3
"""Generate small Android/edge projections. No translation or spelling correction.
Run --check in CI to detect stale projections; edit only data/bodo/lexicon.json.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / "data/bodo/lexicon.json").read_text())
entries = source["entries"]
ids = set()
forms = {}
for entry in entries:
    assert entry["id"] not in ids, "Duplicate lexicon ID"
    ids.add(entry["id"])
    assert entry["sources"], "Provenance required"
    assert entry["meaningStatus"] in ("verified", "user_confirmed", "provisional")
    for form in entry["roman"] + entry["devanagari"]:
        key = form.casefold()
        assert key not in forms, f"Ambiguous form {form}: model as separate senses instead"
        forms[key] = entry["id"]

prompt = """Bodo interpretation reference (not a translator):
Recognize Romanized and Devanagari Bodo; preserve the original input, spelling, numbers and negation.
Use full sentence context, not English/Hindi resemblance or stale conversation assumptions.
These are glosses, not grammar rules. Do not substitute words globally or assume a whole sentence's meaning.
user_confirmed means custom product intent, not independent linguistic verification.
provisional means inherited unverified material; do not present it as verified knowledge.
A single short token (na, ma, dao, etc.) is not enough to identify a language.
When meaning is genuinely uncertain, ask one concise clarification; do not silently change the subject.
Reply in the explicitly requested language/script; otherwise use the selected Bodo script.
For voice: transcribe what was spoken, not what the reference suggests should have been spoken.
"""
for e in entries:
    prompt += f"- {' / '.join(e['roman'] + e['devanagari'])}: {'; '.join(e['meanings'])} ({e['partOfSpeech']}; meaning={e['meaningStatus']}; forms={e['formStatus']}). {e['notes']}\n"

q = lambda value: json.dumps(value, ensure_ascii=False)
# JSON escaping is also valid for these Kotlin literals; protect Kotlin interpolation.
kq = lambda value: q(value).replace('$', '\\$')
kotlin = '''// Generated by scripts/generate-bodo-lexicon.py; do not edit.
package com.example.data.language

import java.text.Normalizer
import java.util.Locale

data class BodoLexiconEntry(
    val id: String,
    val roman: List<String>,
    val devanagari: List<String>,
    val meanings: List<String>,
    val meaningStatus: String,
    val formStatus: String
)

object BodoLexicon {
'''
kotlin += f'    const val VERSION = {kq(source["version"])}\n'
kotlin += '    val entries: List<BodoLexiconEntry> = listOf(\n'
for e in entries:
    kl = lambda xs: 'listOf(' + ', '.join(kq(x) for x in xs) + ')'
    kotlin += f'        BodoLexiconEntry({kq(e["id"])}, {kl(e["roman"])}, {kl(e["devanagari"])}, {kl(e["meanings"])}, {kq(e["meaningStatus"])}, {kq(e["formStatus"])}),\n'
kotlin += '''    )
    private fun key(text: String): String =
        Normalizer.normalize(text, Normalizer.Form.NFC).lowercase(Locale.ROOT)
    private val index = entries.flatMap { entry ->
        (entry.roman + entry.devanagari).map { key(it) to entry }
    }.toMap()
    fun lookup(word: String): BodoLexiconEntry? = index[key(word)]
    // Lookup only: never normalize, transliterate or rewrite the actual request.
    fun matches(text: String): List<BodoLexiconEntry> =
        Regex("[\\\\p{L}\\\\p{M}']+").findAll(text).mapNotNull { lookup(it.value) }
            .distinctBy { it.id }.toList()
'''
kotlin += f'    const val PROMPT_REFERENCE = {kq(prompt)}\n}}\n'
outputs = {
    ROOT / 'app/src/main/java/com/example/data/language/BodoLexicon.kt': kotlin,
    ROOT / 'supabase/functions/_shared/bodo-lexicon.generated.ts':
        '// Generated by scripts/generate-bodo-lexicon.py; do not edit.\n'
        + 'export const lexicon = ' + json.dumps(source, ensure_ascii=False, indent=2) + ';\n'
        + 'export const BODO_REFERENCE = ' + q(prompt) + ';\n',
}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, content in outputs.items():
    if args.check:
        assert path.exists() and path.read_text() == content, f'Stale generated file: {path.relative_to(ROOT)}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
print(f'{len(entries)} entries: ' + ('projections current' if args.check else 'projections generated'))
